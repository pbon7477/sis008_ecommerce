            </p>
            <p>Este derecho podrá ejercerse dentro del plazo legal de seis meses contado desde la recepción del producto, cuando corresponda.</p>

            <p>En caso de que un producto nuevo presente una falla cubierta por la garantía legal, el consumidor podrá elegir entre las siguientes alternativas:
