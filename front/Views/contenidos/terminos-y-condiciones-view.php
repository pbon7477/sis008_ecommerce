            <br>
            <h4>3. Funcionamiento de la tienda y selección de productos</h4>
            <br>
            <p>
                A través de este sitio web, los usuarios podrán visualizar los productos disponibles, consultar sus características, seleccionar aquellos de su interés y agregarlos a un carrito de compras.
            </p>
            <p>
                El carrito permitirá revisar los productos seleccionados, modificar sus cantidades, eliminar artículos y consultar el resumen de los productos solicitados.
            </p>
            <p>
                Una vez finalizada la selección, el usuario deberá proporcionar los datos necesarios para gestionar su pedido, incluyendo:
            </p>
            <ul>

                <li> Nombre del cliente.</li>
                <li> Dirección de correo electrónico.</li>
                <li> Dirección física de entrega, cuando corresponda.</li>
                <li> Número de teléfono celular.</li>
            </ul>
            <br>
            <p>
                El usuario será responsable de proporcionar información correcta, completa y actualizada, especialmente aquella necesaria para establecer contacto y coordinar la entrega de los productos.
            </p>
            <br>
            <br>

            <h4>4. Solicitud y confirmación de pedidos mediante WhatsApp</h4>
            <br>
            <p>
                Una vez completada la selección de productos y los datos solicitados, el sitio web mostrará un resumen del pedido para que el usuario pueda revisar la información antes de continuar.
            </p>
            <p>
                Posteriormente, el sistema generará un mensaje con los antecedentes del pedido y abrirá la aplicación WhatsApp del dispositivo del usuario para que este pueda enviarlo a la tienda.
            </p>

            <p>
                **La generación del mensaje y la apertura de WhatsApp no implican, por sí solas, que el pedido haya sido recibido o confirmado por la tienda.** El usuario deberá enviar efectivamente el mensaje para que la solicitud pueda ser recibida y gestionada.
            </p>

            <p>
                Una vez recibido el mensaje, la tienda revisará la solicitud y se comunicará con el cliente para:
            </p>
            <ul>
                <li>Verificar la disponibilidad de los productos solicitados.</li>
                <li>Confirmar los precios y las cantidades.</li>
                <li>Informar los costos y condiciones de despacho o entrega, cuando corresponda.</li>
                <li>Coordinar el medio y las condiciones de pago.</li>
                <li>Acordar los detalles necesarios para completar la operación.</li>
            </ul>


            <p>
                La compraventa quedará sujeta a la aceptación de las condiciones definitivas por ambas partes y a la confirmación de la operación por parte de la tienda, sin perjuicio de las reglas legales sobre formación del consentimiento y contratación electrónica.
            </p>
            <p>
                Una vez perfeccionada la compraventa, la tienda proporcionará al cliente una confirmación escrita de la operación por el medio de comunicación previamente informado.
