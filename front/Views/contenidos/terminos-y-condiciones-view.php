                <li>Los costos asociados al despacho o entrega.</li>
                <li>Los plazos estimados de entrega o la fecha de disponibilidad para retiro.</li>
            </ul>
            <br>
            <p>El cliente será responsable de proporcionar una dirección correcta y de facilitar la recepción de los productos.
