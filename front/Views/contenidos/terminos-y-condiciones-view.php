                <li>Contactar al cliente para confirmar las condiciones de la operación.</li>
                <li>Coordinar los pagos, despachos y entregas correspondientes.</li>
                <li>Mantener los registros necesarios para cumplir las obligaciones legales aplicables.</li>
            </ul>

            <p>El tratamiento de los datos personales se realizará conforme a la legislación chilena vigente y a lo establecido en la Política de Privacidad de este sitio web, disponible en la sección correspondiente.
